#!/usr/bin/env node
// The home page's "Featured" card photos (lib/catalog/copy.ts `featured`).
//
// Each card shows the photo for its pick (the women's / men's model photo when
// it says photo: "womens" / "mens", the flat shot when it says photo: "flat"), cropped head-to-hips like the other home cards when
// it's a full-body shot (scripts/card-crop.mjs). Made from the site's own
// catalog images, so it never needs catalog.json. Writes public/images/featured/
// and lib/catalog/featured.generated.ts. gen-catalog.mjs runs it at the end;
// after changing a pick or photo in copy.ts:  npm run featured
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cardCrop, writeCard } from "./card-crop.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "images", "featured");
const TS_OUT = path.join(ROOT, "lib", "catalog", "featured.generated.ts");

const { featured } = await import("../lib/catalog/copy.ts");
const { getShopProduct } = await import("../lib/catalog/index.ts");
const { imageSetFor, imagesFor, normalizeSelection } = await import("../lib/catalog/select.ts");

const images = {};
const writes = [];
for (const f of featured.items) {
  const p = getShopProduct(f.slug);
  if (!p) {
    console.warn(`warn: featured ${f.slug}: no such product (left off the home page)`);
    continue;
  }
  const sel = normalizeSelection(p, f.pick ?? {});
  const set = imageSetFor(p, sel);
  const photos = set?.images ?? imagesFor(p, sel);
  const want = { womens: /model-womens/, mens: /model-mens/, flat: /-flat\.|\/flat\./ }[f.photo ?? ""];
  const photo = (want && photos.find((s) => want.test(s))) || photos[0];
  if (want && !want.test(photo)) console.warn(`warn: featured ${f.slug}: no ${f.photo} photo for ${JSON.stringify(f.pick ?? {})}`);
  // the product's own card already is this photo, cropped
  if (p.card && p.card.startsWith(photo.replace(/\.webp$/, "-card"))) {
    images[f.slug] = p.card;
    continue;
  }
  const file = path.join(ROOT, "public", photo);
  const crop = fs.existsSync(file) ? await cardCrop(file) : null;
  if (!crop) {
    images[f.slug] = photo;
    continue;
  }
  const hash = crypto.createHash("sha256").update(fs.readFileSync(file)).update(JSON.stringify(crop)).digest("hex").slice(0, 8);
  const name = `${f.slug}.${hash}.webp`;
  writes.push({ file, crop, out: path.join(OUT_DIR, name) });
  images[f.slug] = `/images/featured/${name}`;
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
for (const w of writes) await writeCard(w.file, w.crop, w.out);
fs.writeFileSync(
  TS_OUT,
  `// GENERATED by scripts/gen-featured.mjs from lib/catalog/copy.ts \`featured\`. Do not edit by hand.\n` +
    `// The home page's Featured card photo per product slug.\n` +
    `export const featuredCardImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`
);
console.log(`featured: ${Object.keys(images).length} cards (${writes.length} cropped) -> lib/catalog/featured.generated.ts`);
