#!/usr/bin/env node
// Size guides for the product pages, from Printful's public catalog
// (GET https://api.printful.com/products/<id>/sizes: no token needed), for every
// Printful catalog product the line-up uses. Writes lib/catalog/sizes.generated.ts.
//
//   node scripts/gen-sizes.mjs
//
// Uses the "product_measure" table (the garment laid flat, in inches). Printful
// labels some columns A/B/C and explains them in its diagram text; those are
// turned into names here. Fit notes are ours (FIT below), not Printful's.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(ROOT, "lib/catalog/products.generated.ts"), "utf8");
const ids = [...new Set([...src.matchAll(/"printfulCatalogProductId": (\d+)/g)].map((m) => Number(m[1])))].sort((a, b) => a - b);

// One line per garment family (John, 2026-10-12).
const FIT = {
  586: "Relaxed, heavyweight; true to size.",
  1414: "Runs slim — size up.",
  636: "Cropped, boxy.",
  810: "Regular fit.",
  315: "Fitted top, flared skirt; between sizes, size up.",
  99: "One size, adjustable snap.",
  1481: "Elastic waist, short 2⅝″ inseam; between sizes, size up.",
};

const NAMES = [
  [/^1\/2 chest width$|^width$|^chest width$/i, "Chest width (laid flat)"],
  [/^1\/2 waist width$/i, "Waist width (laid flat)"],
  [/^length$/i, "Length"],
  [/^sleeve length$/i, "Sleeve length"],
  [/^inseam length$/i, "Inseam"],
  [/^front rise$/i, "Front rise"],
];
const nameFor = (label) => NAMES.find(([re]) => re.test(label.trim()))?.[1] ?? label.trim();

/** Printful's diagram text, e.g. "A 1/2 chest width B length C sleeve length" -> { A: "1/2 chest width", ... } */
function letterNames(text) {
  const plain = String(text ?? "").replace(/<[^>]+>/g, " ").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ").trim();
  const out = {};
  for (const m of plain.matchAll(/\b([A-F]) ([A-Za-z/1-9 ]+?)(?= Place| [A-F] |$)/g)) out[m[1]] = m[2].trim();
  return out;
}

// To the nearest 1/8 inch, written the US way: 20.25 -> "20¼", 17.32 -> "17⅜".
const EIGHTHS = ["", "⅛", "¼", "⅜", "½", "⅝", "¾", "⅞"];
const fmt = (v) => {
  const n = Number(v);
  if (!Number.isFinite(n)) return String(v);
  const e = Math.round(n * 8);
  return `${Math.floor(e / 8)}${EIGHTHS[e % 8]}`;
};

const guides = {};
for (const id of ids) {
  const r = await fetch(`https://api.printful.com/products/${id}/sizes`);
  const j = await r.json();
  if (j.code !== 200) throw new Error(`product ${id}: ${j.code} ${JSON.stringify(j.result).slice(0, 100)}`);
  const t = j.result.size_tables.find((x) => x.type === "product_measure");
  if (!t) throw new Error(`product ${id}: no product_measure table`);
  if (t.unit !== "inches") throw new Error(`product ${id}: unit ${t.unit}`);
  const letters = letterNames(t.image_description);
  let rows = t.measurements.map((m) => {
    const label = /^[A-F]$/.test(m.type_label) ? letters[m.type_label] ?? m.type_label : m.type_label;
    return {
      label: nameFor(label),
      values: Object.fromEntries(
        m.values.map((v) => [v.size, v.value != null ? fmt(v.value) : `${fmt(v.min_value)}–${fmt(v.max_value)}`])
      ),
    };
  });
  // The hat: only the head size means anything to a buyer.
  if (id === 99) rows = rows.slice(0, 1).map((r) => ({ ...r, label: "Fits head size" }));
  if (rows.some((r) => /^[A-F]$/.test(r.label))) throw new Error(`product ${id}: unnamed column ${rows.map((r) => r.label)}`);
  guides[id] = { sizes: j.result.available_sizes, rows, fit: FIT[id] ?? null };
  console.log(`${id}: ${rows.map((r) => r.label).join(", ")} · ${j.result.available_sizes.join(" ")}`);
}

const ts =
  `// GENERATED by scripts/gen-sizes.mjs from Printful's public catalog (product measurements,\n` +
  `// laid flat, inches). Do not edit by hand; fit notes live in the script.\n\n` +
  `export type SizeGuide = {\n  sizes: string[];\n  rows: { label: string; values: Record<string, string> }[];\n  /** Our one-line fit note. */\n  fit: string | null;\n};\n\n` +
  `export const sizeGuides: Record<number, SizeGuide> = ${JSON.stringify(guides, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, "lib/catalog/sizes.generated.ts"), ts);
console.log(`wrote lib/catalog/sizes.generated.ts (${ids.length} garments)`);
