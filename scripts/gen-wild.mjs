#!/usr/bin/env node
// "Out in the wild" photos for the home page, from the gallery manifest
// (scratchpad mop-gallery/manifest.json) and the selection in scripts/wild/photos.json.
//
//   node scripts/gen-wild.mjs /path/to/mop-gallery/manifest.json
//
// For every photo NOT marked `hidden` it writes, into public/images/wild/ (replaced):
//   <nn>.<hash>.webp      the lightbox photo, long side 1000 px
//   <nn>-sq.<hash>.webp   the home-grid square, 500 px, framed on the face(s) and shirt
//   <nn>-sm.<hash>.webp   the same square at 240 px, for the strip at the top of the home page
// and lib/wild.generated.ts. Hidden photos never get files, so they stay out of
// the public repo until someone flips `hidden` and re-runs this.
//
// Per photo in photos.json: design (caption), href (product page), alt (the
// shirt, never the person), faces ([x, y, w, h] fractions of the manifest's
// candidate file, from macOS Vision), and optionally source: "source" (use the
// manifest's full-size source_path) with crop: [x0, y0, x1, y1] fractions.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public/images/wild");
const TS_OUT = path.join(ROOT, "lib/wild.generated.ts");
const { photos } = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/wild/photos.json"), "utf8"));

/** photos.json `person` (an id, or a list when several people are in the photo) -> people. */
export function peopleOf(p) {
  const list = (Array.isArray(p.person) ? p.person : [p.person]).filter((x) => typeof x === "string" && x.trim());
  if (!list.length) throw new Error(`photo ${p.n} has no person: tag it in scripts/wild/photos.json (an anonymous id like "p14")`);
  return list;
}

function writeTs(out) {
  const ts =
    `// GENERATED by scripts/gen-wild.mjs from the gallery manifest + scripts/wild/photos.json. Do not edit by hand.\n` +
    `// "Out in the wild" photos on the home page (hidden ones are left out).\n\n` +
    `export type WildPhoto = {\n  n: string;\n  /** Caption: the design, linked to href. */\n  design: string;\n  href: string;\n  /** Describes the shirt, never the person. */\n  alt: string;\n  /** Who is in it (anonymous ids): never twice in the strip, never side by side in the grid. */\n  people: string[];\n  /** Lightbox photo (long side 1000 px) and its size. */\n  src: string;\n  width: number;\n  height: number;\n  /** Home-grid square (500 px). */\n  square: string;\n  /** The same square at 240 px (the strip at the top of the home page). */\n  small: string;\n};\n\n` +
    `export const wildPhotos: WildPhoto[] = ${JSON.stringify(out, null, 2)};\n`;
  fs.writeFileSync(TS_OUT, ts);
}

// --people-only: update who is in each photo (photos.json `person`) without the gallery
// manifest; the images and everything else stay as they are.
if (process.argv[2] === "--people-only") {
  const { wildPhotos } = await import(path.join(ROOT, "lib/wild.generated.ts"));
  const byN = Object.fromEntries(photos.map((p) => [p.n, p]));
  const out = wildPhotos.map(({ people: _old, ...w }) => {
    const p = byN[w.n];
    if (!p || p.hidden) throw new Error(`photo ${w.n} is on the site but ${p ? "hidden" : "missing"} in photos.json: run the full script`);
    const { n, design, href, alt, ...rest } = w;
    return { n, design, href, alt, people: peopleOf(p), ...rest };
  });
  writeTs(out);
  console.log(`people updated for ${out.length} photos -> lib/wild.generated.ts`);
  process.exit(0);
}

const manifestPath = process.argv[2];
if (!manifestPath) {
  console.error("usage: node scripts/gen-wild.mjs <mop-gallery/manifest.json>   (or --people-only)");
  process.exit(2);
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const byNumber = Object.fromEntries(manifest.candidates.map((c) => [c.number, c]));

const hash8 = (buf) => crypto.createHash("sha256").update(buf).digest("hex").slice(0, 8);
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

/** The square to cut from a W×H image: full width (portrait) or height (landscape), framed on the faces. */
export function squareFor(W, H, faces) {
  const side = Math.min(W, H);
  const box = faces.length
    ? faces.reduce((a, [x, y, w, h]) => [Math.min(a[0], x), Math.min(a[1], y), Math.max(a[2], x + w), Math.max(a[3], y + h)], [1, 1, 0, 0])
    : [0.4, 0.15, 0.6, 0.3];
  if (H >= W) {
    // a little headroom above the top face; the shirt fills the rest
    const top = clamp(Math.round(box[1] * H - side * 0.1), 0, H - side);
    return { left: 0, top, width: side, height: side };
  }
  const cx = ((box[0] + box[2]) / 2) * W;
  return { left: clamp(Math.round(cx - side / 2), 0, W - side), top: 0, width: side, height: side };
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
const out = [];
for (const p of photos) {
  if (p.hidden) continue;
  const c = byNumber[p.n];
  if (!c) throw new Error(`photo ${p.n} is not in the manifest`);
  const file = p.source === "source" ? c.source_path : path.resolve(path.dirname(manifestPath), c.candidate_file);
  if (!fs.existsSync(file)) throw new Error(`photo ${p.n}: missing ${file}`);
  // honour EXIF orientation once, then work on the upright pixels
  const upright = await sharp(file).rotate().toBuffer({ resolveWithObject: true });
  let img = sharp(upright.data);
  let W = upright.info.width;
  let H = upright.info.height;
  let faces = p.faces ?? [];
  if (p.crop) {
    const [x0, y0, x1, y1] = p.crop;
    const region = { left: Math.round(x0 * W), top: Math.round(y0 * H), width: Math.round((x1 - x0) * W), height: Math.round((y1 - y0) * H) };
    img = sharp(await sharp(upright.data).extract(region).toBuffer());
    // faces were measured on the uncropped candidate
    faces = faces.map(([x, y, w, h]) => [(x - x0) / (x1 - x0), (y - y0) / (y1 - y0), w / (x1 - x0), h / (y1 - y0)]);
    W = region.width;
    H = region.height;
  }
  const base = await img.toBuffer();
  const full = await sharp(base)
    .resize({ width: W >= H ? 1000 : undefined, height: H > W ? 1000 : undefined, withoutEnlargement: true })
    .webp({ quality: 80 })
    .toBuffer({ resolveWithObject: true });
  const square = squareFor(W, H, faces);
  const sq = await sharp(base).extract(square).resize({ width: 500, height: 500 }).webp({ quality: 78 }).toBuffer();
  const sm = await sharp(base).extract(square).resize({ width: 240, height: 240 }).webp({ quality: 74 }).toBuffer();
  const fullName = `${p.n}.${hash8(full.data)}.webp`;
  const sqName = `${p.n}-sq.${hash8(sq)}.webp`;
  const smName = `${p.n}-sm.${hash8(sm)}.webp`;
  fs.writeFileSync(path.join(OUT_DIR, fullName), full.data);
  fs.writeFileSync(path.join(OUT_DIR, sqName), sq);
  fs.writeFileSync(path.join(OUT_DIR, smName), sm);
  out.push({
    n: p.n,
    design: p.design,
    href: p.href,
    alt: p.alt,
    people: peopleOf(p),
    src: `/images/wild/${fullName}`,
    width: full.info.width,
    height: full.info.height,
    square: `/images/wild/${sqName}`,
    small: `/images/wild/${smName}`,
  });
  console.log(`${p.n}  ${full.info.width}x${full.info.height}  ${Math.round(full.data.length / 1024)} KB + square ${Math.round(sq.length / 1024)} KB  ${p.design}`);
}

writeTs(out);
console.log(`${out.length} photos (${photos.filter((p) => p.hidden).length} hidden) -> public/images/wild/, lib/wild.generated.ts`);
